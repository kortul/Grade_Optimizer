import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const renderer=readFileSync(new URL('../webgpu-forest-lab.v14.js',import.meta.url),'utf8');
const html=readFileSync(new URL('../webgpu-forest-lab.html',import.meta.url),'utf8');
const atmosphere=readFileSync(new URL('../webgpu-forest-atmosphere.v3.js',import.meta.url),'utf8');

assert.match(renderer,/shareStageOneMaterialsByKind\(root,\{defaultKind:'slopes'\}\)/,'Stage 1 semantic groups must still be recognised');
assert.match(renderer,/object\.material\.map\(\(\)=>snowMaterial\)/,'winter material replacement must remain intact');
assert.match(renderer,/new THREE\.WebGPURenderer\(\{ antialias: true, powerPreference: 'high-performance' \}\)/,'V14 must initialize the 4-sample antialiasing path');
assert.match(renderer,/renderer\.backend\.isWebGPUBackend === true/,'the visible label must identify the actual WebGPU backend or WebGL fallback');
assert.match(renderer,/name:'Norway'[\s\S]*name:'Alpine'[\s\S]*name:'Broad'/,'V14 must provide three spruce morphologies');
assert.match(renderer,/levels:24,branches:7,width:1\.02/,'Norway spruce must use a dense classic crown');
assert.match(renderer,/levels:26,branches:6,width:0\.86/,'Alpine spruce must be tall and narrow');
assert.match(renderer,/levels:22,branches:8,width:1\.16/,'Broad spruce must have a mature wide silhouette');
assert.match(renderer,/const needleCount=high\?20:mid\?12:6/,'V14 needle sprays must be denser at every LOD');
assert.match(renderer,/const twigStations=high\?6:mid\?4:2/,'V14 must increase irregular lateral branching');
assert.match(renderer,/const radiusSide=size\*0\.34,radiusUp=size\*0\.29,radiusAlong=size\*0\.18/,'needle clumps must occupy a wider 3D volume');
assert.match(renderer,/new THREE\.QuadraticBezierCurve3/,'branches must be curved');
assert.match(renderer,/const gapWeights=Array\.from/,'branch azimuths must be irregular rather than evenly spaced');
assert.match(renderer,/while\(r2>1\)/,'needle roots must be sampled volumetrically');
assert.match(renderer,/tertiary shoot/,'near branches must carry irregular tertiary shoots');
assert.match(renderer,/sizeClass<0\.38\?6\.5\+rr\(\)\*5\.5:sizeClass<0\.84\?11\+rr\(\)\*6:17\+rr\(\)\*6/,'trees must use small, medium and large size bands');
assert.match(renderer,/function selectTreeLod\(distance,current\)/,'LOD selection must use per-tree hysteresis');
assert.match(renderer,/current==='near'&&distance>=115&&distance<300/,'near LOD must have a hysteresis band');
assert.match(renderer,/current==='mid'&&distance>=230&&distance<1060/,'mid LOD must have a hysteresis band');
assert.match(renderer,/const cellSize=300/,'forest instances must remain split into tighter spatial cells');
assert.doesNotMatch(renderer,/cameraTurned/,'camera rotation alone must not rebuild all forest batches');
assert.match(renderer,/const previousGroup=forestSystem\.group/,'new LOD batches must be swapped atomically');
assert.match(renderer,/new THREE\.InstancedMesh/,'trees must remain instanced');
assert.match(renderer,/mesh\.computeBoundingSphere\(\);mesh\.frustumCulled=true;/,'spatial batches must use frustum culling');
assert.match(renderer,/mesh\.receiveShadow=lod==='near'/,'only near trees should receive shadows');
assert.match(renderer,/frameTimeEMA>21/,'adaptive resolution must react around a 60 FPS frame budget');
assert.match(renderer,/atmosphere\.setResolutionScale\(dynamicResolutionScale\)/,'adaptive scale must reach the renderer through the atmosphere');
assert.match(renderer,/sunLight\.shadow\.mapSize\.setScalar\(512\)/,'shadow map must be reduced to 512');
assert.match(renderer,/sunLight\.shadow\.camera\.far=2200/,'shadow distance must be reduced');
assert.match(html,/webgpu-forest-lab\.v14\.js\?v=20261126b/,'main HTML must activate V14');

assert.match(atmosphere,/function setResolutionScale\(scale\)/,'atmosphere must expose adaptive scaling');
assert.match(atmosphere,/balanced:1\.0/,'balanced mode must target native 1080p scale');
assert.match(atmosphere,/Math\.max\(0\.85,qualityScale\*dynamicResolutionScale\)/,'dynamic resolution must not fall below the quality floor');
assert.match(atmosphere,/new SkyMesh\(\)/,'physical SkyMesh must remain active');
assert.match(atmosphere,/pmremGenerator\.fromScene\(environmentScene, 0\.035\)/,'PBR IBL must remain sky-derived');
assert.match(atmosphere,/renderer\.render\(scene, camera\)/,'direct renderer path must remain active');
